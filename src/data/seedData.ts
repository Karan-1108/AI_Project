// Generate 550 realistic Teacher Grading Records to populate the Random Forest model
export function generateSeedTeacherGradingRecords(): TeacherGradingRecord[] {
  const records: TeacherGradingRecord[] = [];
  const questionTypes = ['mcq', 'short_answer', 'descriptive', 'code_question'];

  for (let i = 0; i < 550; i++) {
    // Generate realistic correlated feature distributions
    const correctness = Math.min(1.0, Math.max(0.2, 0.4 + Math.random() * 0.55));
    const explanationDepth = Math.min(1.0, Math.max(0.1, correctness * 0.85 + (Math.random() * 0.3 - 0.15)));
    const presentationScore = Math.min(1.0, Math.max(0.3, 0.45 + Math.random() * 0.5));
    const keywordDensity = Math.min(1.0, Math.max(0.2, correctness * 0.7 + Math.random() * 0.3));
    const effortWeight = Math.min(1.0, Math.max(0.4, 0.5 + Math.random() * 0.5));
    const questionDifficulty = 0.2 + Math.random() * 0.7;

    // Realistic teacher grading formula with slight human noise
    let trueGrade = 
      (correctness * 48) +
      (explanationDepth * 22) +
      (presentationScore * 14) +
      (keywordDensity * 8) +
      (effortWeight * 5) +
      ((1 - questionDifficulty) * 3) +
      ((Math.random() - 0.5) * 3); // realistic ±1.5% grading variance

    trueGrade = Math.min(100, Math.max(0, Math.round(trueGrade * 10) / 10));

    const studentIds = ['24BDS0162', '24BCE2930', '24BCI0287'];
    records.push({
      id: `tgr_${i + 1}`,
      studentId: studentIds[i % studentIds.length],
      correctness: parseFloat(correctness.toFixed(2)),
      presentationScore: parseFloat(presentationScore.toFixed(2)),
      effortWeight: parseFloat(effortWeight.toFixed(2)),
      explanationDepth: parseFloat(explanationDepth.toFixed(2)),
      keywordDensity: parseFloat(keywordDensity.toFixed(2)),
      questionDifficulty: parseFloat(questionDifficulty.toFixed(2)),
      teacherGrade: trueGrade,
      questionType: questionTypes[i % questionTypes.length],
      timestamp: new Date(Date.now() - (550 - i) * 3600000 * 4).toISOString(),
    });
  }

  return records;
}

